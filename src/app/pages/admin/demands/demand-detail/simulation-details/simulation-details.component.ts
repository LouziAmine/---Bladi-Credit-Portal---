import { ChangeDetectionStrategy, Component, computed, inject, input, signal } from '@angular/core';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { TranslatePipe, TranslateService } from '@ngx-translate/core';
import { DemandAmortizationResponse } from '../../../../../core/models/demand.model';
import { ErrorMessageComponent } from '../../../../../shared/components/error-message/error-message.component';
import { LoadingSpinnerComponent } from '../../../../../shared/components/loading-spinner/loading-spinner.component';
import { formatAmount, formatPercent } from '../../../../../core/utils/format.utils';

const CB_GREEN: [number, number, number] = [15, 92, 61];

interface AmortizationSummary {
  monthlyPayment: number;
  totalInterest: number;
  totalCost: number;
  annualDebtService: number | null;
}

export function summarizeAmortization(data: DemandAmortizationResponse): AmortizationSummary | null {
  if (data.enterprise) {
    return { ...data.enterprise };
  }
  if (data.conventional) {
    return { ...data.conventional, annualDebtService: null };
  }
  if (data.mourabaha) {
    return {
      monthlyPayment: data.mourabaha.monthlyPaymentTtc,
      totalInterest: data.mourabaha.marginTtc,
      totalCost: data.amount + data.mourabaha.marginTtc,
      annualDebtService: null,
    };
  }
  return null;
}

@Component({
  changeDetection: ChangeDetectionStrategy.OnPush,
  selector: 'app-simulation-details',
  imports: [ErrorMessageComponent, LoadingSpinnerComponent, TranslatePipe],
  templateUrl: './simulation-details.component.html',
})
export class SimulationDetailsComponent {
  private readonly translate = inject(TranslateService);

  readonly amortization = input<DemandAmortizationResponse | null>(null);
  readonly loading = input(false);
  readonly errorMessage = input<string | null>(null);
  readonly compact = input(false);
  readonly title = input('simulationDetails.defaultTitle');
  readonly subtitle = input('simulationDetails.defaultSubtitle');
  readonly icon = input('bi-calculator');

  protected readonly showSchedule = signal(false);
  protected readonly summary = computed(() => {
    const data = this.amortization();
    return data ? summarizeAmortization(data) : null;
  });

  readonly formatAmount = formatAmount;
  readonly formatPercent = formatPercent;

  toggleSchedule(): void {
    this.showSchedule.update((v) => !v);
  }

  downloadPdf(): void {
    const data = this.amortization();
    const summary = this.summary();
    if (!data || !summary) {
      return;
    }

    const t = (key: string): string => this.translate.instant(key);
    const title = t(this.title());
    const subtitle = t(this.subtitle());

    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();

    doc.setFontSize(16);
    doc.setTextColor(...CB_GREEN);
    doc.text('Credit Bladi', 14, 18);
    doc.setFontSize(9);
    doc.setTextColor(120);
    doc.text(t('simulationDetails.pdf.autoGenerated'), 14, 24);
    doc.setDrawColor(220);
    doc.line(14, 28, pageWidth - 14, 28);

    doc.setFontSize(13);
    doc.setTextColor(20);
    doc.text(title, 14, 38);
    doc.setFontSize(9);
    doc.setTextColor(100);
    doc.text(subtitle, 14, 44);
    doc.text(`${t('simulationDetails.pdf.case')} ${data.reference}`, 14, 50);
    doc.text(
      `${t('simulationDetails.pdf.generatedOn')} ${new Date().toLocaleDateString()}`,
      pageWidth - 14, 50, { align: 'right' },
    );

    autoTable(doc, {
      startY: 56,
      head: [[
        t('simulationDetails.amount'), t('simulationDetails.duration'), t('simulationDetails.applicableRate'),
        t('simulationDetails.monthlyPayment'), t('simulationDetails.insurancePremium'),
        t('simulationDetails.allInMonthlyPayment'),
      ]],
      body: [[
        this.formatAmount(data.amount),
        `${data.duration} ${t('mortgageCredit.form.months')}`,
        this.formatPercent(data.applicableRate),
        this.formatAmount(summary.monthlyPayment),
        this.formatAmount(data.insurancePremium),
        this.formatAmount(data.allInMonthlyPayment),
      ]],
      theme: 'grid',
      headStyles: { fillColor: CB_GREEN },
      styles: { fontSize: 9 },
    });

    autoTable(doc, {
      startY: (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 6,
      head: [[
        t('simulationDetails.totalInterest'), t('simulationDetails.totalCost'), t('simulationDetails.taeg'),
        t('simulationDetails.processingFees'), t('simulationDetails.totalInsuranceCost'),
        t('simulationDetails.annualDebtService'),
      ]],
      body: [[
        this.formatAmount(summary.totalInterest),
        this.formatAmount(summary.totalCost),
        this.formatPercent(data.taeg),
        this.formatAmount(data.processingFees),
        this.formatAmount(data.totalInsuranceCost),
        summary.annualDebtService != null ? this.formatAmount(summary.annualDebtService) : '-',
      ]],
      theme: 'grid',
      headStyles: { fillColor: CB_GREEN },
      styles: { fontSize: 9 },
    });

    const scheduleY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;
    doc.setFontSize(11);
    doc.setTextColor(20);
    doc.text(
      `${t('simulationDetails.schedule')} (${data.amortizationSchedule.length} ${t('mortgageCredit.schedule.installments')})`,
      14, scheduleY,
    );

    autoTable(doc, {
      startY: scheduleY + 4,
      head: [[
        t('mortgageCredit.schedule.col.num'), t('mortgageCredit.schedule.col.beginningBalance'),
        t('mortgageCredit.schedule.col.interest'), t('mortgageCredit.schedule.col.principal'),
        t('mortgageCredit.schedule.col.insurance'), t('mortgageCredit.schedule.col.installment'),
        t('mortgageCredit.schedule.col.endingBalance'),
      ]],
      body: data.amortizationSchedule.map((row) => [
        row.installmentNumber,
        this.formatAmount(row.beginningBalance),
        this.formatAmount(row.interest ?? 0),
        this.formatAmount(row.principal),
        this.formatAmount(data.insurancePremium),
        this.formatAmount(row.payment + data.insurancePremium),
        this.formatAmount(row.endingBalance),
      ]),
      theme: 'striped',
      headStyles: { fillColor: CB_GREEN },
      styles: { fontSize: 8 },
      didDrawPage: () => {
        doc.setFontSize(8);
        doc.setTextColor(120);
        doc.text(
          t('simulationDetails.pdf.bamCompliant'), 14, doc.internal.pageSize.getHeight() - 10,
        );
      },
    });

    this.savePdf(doc, `simulation-${data.reference}-${this.slugify(title)}.pdf`);
  }

  protected savePdf(doc: jsPDF, fileName: string): void {
    doc.save(fileName);
  }

  private slugify(value: string): string {
    return value
      .toLowerCase()
      .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
  }
}
